#!/usr/bin/env bash
# Detect captain rulings written into captain-owned data/captain-replies.md.
#
# With no arguments, this is the tracked target of the one global registered
# watcher check at state/captain-ruling.check.sh, but the file-backed ruling channel is not authenticated.
# Under the accepted single-user threat model, a compromised local process can fabricate a ruling because it already runs as the captain's UID and can modify tracked scripts directly.
# Detection is human: a fabricated data/decisions record will not match a ruling the captain remembers making.
# The file remains a fallback because captain rulings normally arrive in chat or on Linear.
# The program never writes the editor surface.
# Under the ruling lock, complete `<id>: <answer>` lines are ingested into the
# program-owned append log before detection or answer reads continue.
# It accepts ids only while the canonical captain queue marks their structured
# captain-kind record replyable, records only a digest of each seen id/answer
# pair in state/.captain-rulings-seen only after the watcher durably appends the
# matching wake, and prints one
# `captain-ruling <id>[,<id>...]` line when a new ruling needs an agent turn.
# It never changes captain-replies.md and never resolves a hold.
# `--answer <id>` gives the handling agent the latest complete answer for one
# still-open captain hold without exposing answer text in the watcher wake.
# Reply detection and answer reads serialize with fm-decision-hold.sh resolve through the shared ruling-resolution lock.
#
# `--install` atomically publishes the home-bound mode-0700 shim and binds its
# bytes through fm-check-register.sh.
# Bootstrap calls this only while the session lock is held, so the check shares
# fm-watch.sh's existing FM_CHECK_INTERVAL cadence and FM_CHECK_TIMEOUT bound.
#
# Usage: fm-captain-ruling-check.sh [--install | --is-installed | --answer <id>]
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
REPLIES="${FM_CAPTAIN_REPLIES_OVERRIDE:-$FM_HOME/data/captain-replies.md}"
CHECK_ID=captain-ruling
CHECK="$STATE/$CHECK_ID.check.sh"
SEEN="$STATE/.captain-rulings-seen"
PENDING_ACK="$STATE/.captain-ruling-pending-ack"
CAPTAIN_QUEUE="$SCRIPT_DIR/fm-captain-queue.sh"
RULING_LOCK="$STATE/.captain-ruling-resolution.lock"

# shellcheck source=bin/fm-pr-lib.sh disable=SC1091
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-captain-ruling-log-lib.sh disable=SC1091
. "$SCRIPT_DIR/fm-captain-ruling-log-lib.sh"
# shellcheck source=bin/fm-check-lib.sh disable=SC1091
. "$SCRIPT_DIR/fm-check-lib.sh"
# shellcheck source=bin/fm-wake-lib.sh disable=SC1091
. "$SCRIPT_DIR/fm-wake-lib.sh"

ruling_lock_acquire() {
  [ "${FM_CAPTAIN_RULING_LOCK_HELD:-0}" = 1 ] && return 0
  fm_lock_try_acquire "$RULING_LOCK" || return 1
  RULING_LOCK_OWNED=1
}

ruling_lock_release() {
  [ "${RULING_LOCK_OWNED:-0}" = 1 ] || return 0
  fm_lock_release "$RULING_LOCK"
  RULING_LOCK_OWNED=0
}

shim_content() {
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-captain-ruling-check.sh --install.' \
    '# The watcher authenticates these bytes before running the tracked detector.' \
    "export FM_HOME=$(printf '%q' "$FM_HOME")" \
    "exec $(printf '%q' "$SCRIPT_DIR/fm-captain-ruling-check.sh") \"\$@\""
}

check_is_installed() {
  local device
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 1
  device=$(fm_pr_file_device "$STATE") || return 1
  fm_pr_private_file_valid "$CHECK" 700 "$device" \
    && cmp -s "$CHECK" <(shim_content) \
    && fm_custom_check_registered "$STATE" "$CHECK_ID"
}

install_check() {
  local device tmp
  mkdir -p "$STATE" 2>/dev/null || return 1
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 1
  device=$(fm_pr_file_device "$STATE") || return 1

  if check_is_installed; then
    return 0
  fi
  if [ -e "$STATE/$CHECK_ID.meta" ] || [ -L "$STATE/$CHECK_ID.meta" ] \
    || [ -e "$CHECK" ] || [ -L "$CHECK" ] \
    || [ -e "$STATE/$CHECK_ID.check-trust" ] || [ -L "$STATE/$CHECK_ID.check-trust" ]; then
    printf 'fm-captain-ruling-check: legacy captain-ruling task or check must be torn down before installation\n' >&2
    return 1
  fi
  fm_pr_regular_destination_on_device_or_absent "$CHECK" "$device" || return 1
  umask 077
  tmp=$(mktemp "$STATE/.fm-captain-ruling-check.XXXXXX") || return 1
  if ! shim_content > "$tmp" \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device" \
    || ! fm_pr_regular_destination_on_device_or_absent "$CHECK" "$device" \
    || ! mv -f -- "$tmp" "$CHECK"; then
    rm -f -- "$tmp"
    return 1
  fi
  if ! "$SCRIPT_DIR/fm-check-register.sh" "$CHECK_ID" >/dev/null; then
    rm -f -- "$CHECK"
    return 1
  fi
}

captain_queue() {
  [ -x "$CAPTAIN_QUEUE" ] || return 1
  FM_HOME="$FM_HOME" "$CAPTAIN_QUEUE" --json 2>/dev/null
}

captain_hold_is_replyable() {  # <hold-id> <queue-json>
  jq -e --arg id "$1" '
    .schema == "fm-captain-queue.v1"
    and any(.items[]; .id == $id and .replyable == true)
  ' >/dev/null <<< "$2"
}

reply_candidates() {
  fm_ruling_reply_candidates
}

ruling_digest() {
  if command -v shasum >/dev/null 2>&1; then
    { printf '%s' "$1"; printf '\0'; printf '%s' "$2"; } | shasum -a 256 | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    { printf '%s' "$1"; printf '\0'; printf '%s' "$2"; } | sha256sum | awk '{print $1}'
  else
    return 1
  fi
}

publish_seen() {
  local hashes=$1 device tmp
  device=$(fm_pr_file_device "$STATE") || return 1
  if [ -e "$SEEN" ] || [ -L "$SEEN" ]; then
    fm_pr_private_file_valid "$SEEN" 600 "$device" || return 1
  fi
  tmp=$(umask 077; mktemp "$STATE/.fm-captain-rulings-seen.XXXXXX") || return 1
  if { [ ! -e "$SEEN" ] || cat "$SEEN"; printf '%s' "$hashes"; } > "$tmp" \
    && chmod 0600 "$tmp" \
    && fm_pr_private_file_valid "$tmp" 600 "$device" \
    && fm_pr_regular_destination_on_device_or_absent "$SEEN" "$device" \
    && mv -f -- "$tmp" "$SEEN"; then
    return 0
  fi
  rm -f -- "$tmp"
  return 1
}

publish_pending_ack() {
  local ids=$1 hashes=$2 device tmp
  device=$(fm_pr_file_device "$STATE") || return 1
  if [ -e "$PENDING_ACK" ] || [ -L "$PENDING_ACK" ]; then
    fm_pr_private_file_valid "$PENDING_ACK" 600 "$device" || return 1
  fi
  tmp=$(umask 077; mktemp "$STATE/.fm-captain-ruling-pending-ack.XXXXXX") || return 1
  if { printf 'captain-ruling %s\n' "$ids"; printf '%s' "$hashes"; } > "$tmp" \
    && chmod 0600 "$tmp" \
    && fm_pr_private_file_valid "$tmp" 600 "$device" \
    && fm_pr_regular_destination_on_device_or_absent "$PENDING_ACK" "$device" \
    && mv -f -- "$tmp" "$PENDING_ACK"; then
    return 0
  fi
  rm -f -- "$tmp"
  return 1
}

acknowledge_rulings() {
  local notification=${1:-} expected hashes digest device
  [ "$#" -eq 1 ] || return 2
  [ "${FM_CAPTAIN_RULING_WAKE_DURABLE:-0}" = 1 ] || return 1
  device=$(fm_pr_file_device "$STATE") || return 1
  fm_pr_private_file_valid "$PENDING_ACK" 600 "$device" || return 1
  IFS= read -r expected < "$PENDING_ACK" || return 1
  [ "$notification" = "$expected" ] || return 1
  hashes=$(tail -n +2 "$PENDING_ACK") || return 1
  [ -n "$hashes" ] || return 1
  while IFS= read -r digest; do
    [[ "$digest" =~ ^[0-9a-f]{64}$ ]] || return 1
  done <<< "$hashes"
  publish_seen "${hashes}"$'\n' || return 1
  rm -f -- "$PENDING_ACK" || return 1
}

detect_rulings() {
  local id answer answer_digest digest hashes='' ids='' candidates queue
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 0
  if ! fm_ruling_ingest; then
    printf 'captain-ruling-error resolver-log-invalid\n'
    return 0
  fi
  candidates=$(reply_candidates)
  [ -n "$candidates" ] || return 0
  queue=$(captain_queue) || return 0
  while IFS=$'\t' read -r id answer; do
    [ -n "$id" ] && [ -n "$answer" ] || continue
    captain_hold_is_replyable "$id" "$queue" || continue
    answer_digest=$(fm_ruling_sha256 "$answer") || return 0
    fm_ruling_last_record "$id" || return 0
    [ "$FM_RULING_LAST_TYPE" = REPLY ] \
      && [ "$FM_RULING_LAST_DECISION" = "$answer_digest" ] || continue
    digest=$(ruling_digest "$id" "$answer") || return 0
    if { [ -f "$SEEN" ] && grep -Fqx "$digest" "$SEEN"; } \
      || printf '%s' "$hashes" | grep -Fqx "$digest"; then
      continue
    fi
    hashes="${hashes}${digest}"$'\n'
    case ",$ids," in *",$id,"*) ;; *) ids="${ids:+$ids,}$id" ;; esac
  done <<< "$candidates"
  [ -n "$ids" ] || return 0
  publish_pending_ack "$ids" "$hashes" || return 0
  printf 'captain-ruling %s\n' "$ids"
}

answer_for_hold() {
  local id=${1:-} answer queue
  [ "$#" -eq 1 ] || return 2
  fm_pr_task_id_valid "$id" || return 2
  [ -f "$REPLIES" ] && [ ! -L "$REPLIES" ] || {
    printf 'fm-captain-ruling-check: captain replies are unavailable\n' >&2
    return 1
  }
  queue=$(captain_queue) || {
    printf 'fm-captain-ruling-check: captain queue is unavailable\n' >&2
    return 1
  }
  captain_hold_is_replyable "$id" "$queue" || {
    printf 'fm-captain-ruling-check: captain hold is not replyable: %s\n' "$id" >&2
    return 1
  }
  answer=$(fm_ruling_answer "$id") || {
    printf 'fm-captain-ruling-check: no complete answer for captain hold: %s\n' "$id" >&2
    return 1
  }
  printf '%s\n' "$answer"
}

answer_for_locked_resolution() {
  local id=${1:-} answer
  [ "${FM_CAPTAIN_RULING_LOCK_HELD:-0}" = 1 ] || return 1
  [ "$#" -eq 1 ] || return 2
  fm_pr_task_id_valid "$id" || return 2
  answer=$(fm_ruling_answer "$id") || return 1
  printf '%s\n' "$answer"
}

case "${1:-}" in
  '')
    ruling_lock_acquire || exit 0
    detect_rulings
    status=$?
    ruling_lock_release
    exit "$status"
    ;;
  --install) [ "$#" -eq 1 ] || exit 2; install_check ;;
  --is-installed) [ "$#" -eq 1 ] || exit 2; check_is_installed ;;
  --answer)
    shift
    ruling_lock_acquire || {
      printf 'fm-captain-ruling-check: ruling resolution is active\n' >&2
      exit 1
    }
    answer_for_hold "$@"
    status=$?
    ruling_lock_release
    exit "$status"
    ;;
  --answer-locked)
    shift
    answer_for_locked_resolution "$@"
    ;;
  --ack)
    shift
    ruling_lock_acquire || exit 1
    acknowledge_rulings "$@"
    status=$?
    ruling_lock_release
    exit "$status"
    ;;
  *) exit 2 ;;
esac
