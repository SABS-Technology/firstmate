#!/usr/bin/env bash
# Detect captain rulings written into data/pending-decisions.md.
#
# With no arguments, this is the trusted target of the one global registered
# watcher check at state/captain-ruling.check.sh.
# It scans only complete `<id>: <answer>` lines below the `Your replies` heading,
# accepts ids only while tasks-axi reports an active captain hold, records only a
# digest of each seen id/answer pair in state/.captain-rulings-seen, and prints
# one `captain-ruling <id>[,<id>...]` line when a new ruling needs an agent turn.
# It never changes pending-decisions.md and never resolves a hold.
# `--answer <id>` gives the handling agent the latest complete answer for one
# still-open captain hold without exposing answer text in the watcher wake.
#
# `--install` atomically publishes the home-bound mode-0700 shim and binds its
# bytes through fm-check-register.sh.
# Bootstrap calls this only while the session lock is held, so the check shares
# fm-watch.sh's existing FM_CHECK_INTERVAL cadence and FM_CHECK_TIMEOUT bound.
#
# Usage: fm-captain-ruling-check.sh [--install | --answer <id>]
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
PENDING="${FM_PENDING_DECISIONS_OVERRIDE:-$FM_HOME/data/pending-decisions.md}"
CHECK_ID=captain-ruling
CHECK="$STATE/$CHECK_ID.check.sh"
SEEN="$STATE/.captain-rulings-seen"

# shellcheck source=bin/fm-pr-lib.sh disable=SC1091
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-check-lib.sh disable=SC1091
. "$SCRIPT_DIR/fm-check-lib.sh"

shim_content() {
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-captain-ruling-check.sh --install.' \
    '# The watcher authenticates these bytes before running the tracked detector.' \
    "export FM_HOME=$(printf '%q' "$FM_HOME")" \
    "exec $(printf '%q' "$SCRIPT_DIR/fm-captain-ruling-check.sh")"
}

install_check() {
  local device tmp
  mkdir -p "$STATE" 2>/dev/null || return 1
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 1
  device=$(fm_pr_file_device "$STATE") || return 1

  if fm_pr_private_file_valid "$CHECK" 700 "$device" \
    && cmp -s "$CHECK" <(shim_content) \
    && fm_custom_check_registered "$STATE" "$CHECK_ID"; then
    return 0
  fi
  fm_pr_regular_destination_on_device_or_absent "$CHECK" "$device" || return 1
  umask 077
  tmp=$(mktemp "$STATE/.fm-captain-ruling-check.XXXXXX") || return 1
  if ! shim_content > "$tmp" \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device" \
    || ! fm_pr_regular_destination_on_device_or_absent "$CHECK" "$device" \
    || ! mv -f -- "$tmp" "$CHECK"; then
    rm -f -- "$tmp"
    return 1
  fi
  if ! "$SCRIPT_DIR/fm-check-register.sh" "$CHECK_ID" >/dev/null; then
    rm -f -- "$CHECK"
    return 1
  fi
}

show_field() {
  printf '%s\n' "$1" | sed -n "s/^  $2: //p" | head -1
}

captain_hold_is_open() {
  local id=$1 show
  command -v tasks-axi >/dev/null 2>&1 || return 1
  show=$(cd "$FM_HOME" && tasks-axi show "$id" --full 2>/dev/null) || return 1
  # The canonical queue admits captain holds on any task kind. Requiring
  # kind=captain here silently drops real captain decisions on ordinary tasks.
  [ "$(show_field "$show" state)" = queued ] \
    && [ "$(show_field "$show" held)" = yes ] \
    && [ "$(show_field "$show" hold_kind)" = captain ]
}

reply_candidates() {
  local line in_replies=0 id answer
  while IFS= read -r line; do
    line=${line%$'\r'}
    if [ "$in_replies" -eq 0 ]; then
      case "$line" in
        \#*"Your replies"*) in_replies=1 ;;
      esac
      continue
    fi
    case "$line" in \#*) break ;; esac
    case "$line" in *:*) ;; *) continue ;; esac
    id=${line%%:*}
    answer=${line#*:}
    id=${id#"${id%%[![:space:]]*}"}
    id=${id%"${id##*[![:space:]]}"}
    answer=${answer#"${answer%%[![:space:]]*}"}
    answer=${answer%"${answer##*[![:space:]]}"}
    fm_pr_task_id_valid "$id" || continue
    case "$answer" in ''|'<answer>'|'[answer]') continue ;; esac
    printf '%s\t%s\n' "$id" "$answer"
  done < "$PENDING"
}

ruling_digest() {
  if command -v shasum >/dev/null 2>&1; then
    { printf '%s' "$1"; printf '\0'; printf '%s' "$2"; } | shasum -a 256 | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    { printf '%s' "$1"; printf '\0'; printf '%s' "$2"; } | sha256sum | awk '{print $1}'
  else
    return 1
  fi
}

publish_seen() {
  local hashes=$1 device tmp
  device=$(fm_pr_file_device "$STATE") || return 1
  if [ -e "$SEEN" ] || [ -L "$SEEN" ]; then
    fm_pr_private_file_valid "$SEEN" 600 "$device" || return 1
  fi
  tmp=$(umask 077; mktemp "$STATE/.fm-captain-rulings-seen.XXXXXX") || return 1
  if { [ ! -e "$SEEN" ] || cat "$SEEN"; printf '%s' "$hashes"; } > "$tmp" \
    && chmod 0600 "$tmp" \
    && fm_pr_private_file_valid "$tmp" 600 "$device" \
    && fm_pr_regular_destination_on_device_or_absent "$SEEN" "$device" \
    && mv -f -- "$tmp" "$SEEN"; then
    return 0
  fi
  rm -f -- "$tmp"
  return 1
}

detect_rulings() {
  local id answer digest hashes='' ids='' candidates
  [ -f "$PENDING" ] && [ ! -L "$PENDING" ] || return 0
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 0
  candidates=$(reply_candidates)
  [ -n "$candidates" ] || return 0
  while IFS=$'\t' read -r id answer; do
    [ -n "$id" ] && [ -n "$answer" ] || continue
    captain_hold_is_open "$id" || continue
    digest=$(ruling_digest "$id" "$answer") || return 0
    if { [ -f "$SEEN" ] && grep -Fqx "$digest" "$SEEN"; } \
      || printf '%s' "$hashes" | grep -Fqx "$digest"; then
      continue
    fi
    hashes="${hashes}${digest}"$'\n'
    case ",$ids," in *",$id,"*) ;; *) ids="${ids:+$ids,}$id" ;; esac
  done <<< "$candidates"
  [ -n "$ids" ] || return 0
  publish_seen "$hashes" || return 0
  printf 'captain-ruling %s\n' "$ids"
}

answer_for_hold() {
  local id=${1:-} candidate_id candidate_answer candidates answer=''
  [ "$#" -eq 1 ] || return 2
  fm_pr_task_id_valid "$id" || return 2
  [ -f "$PENDING" ] && [ ! -L "$PENDING" ] || {
    printf 'fm-captain-ruling-check: pending decisions are unavailable\n' >&2
    return 1
  }
  captain_hold_is_open "$id" || {
    printf 'fm-captain-ruling-check: captain hold is not open: %s\n' "$id" >&2
    return 1
  }
  candidates=$(reply_candidates)
  while IFS=$'\t' read -r candidate_id candidate_answer; do
    [ "$candidate_id" = "$id" ] || continue
    answer=$candidate_answer
  done <<< "$candidates"
  [ -n "$answer" ] || {
    printf 'fm-captain-ruling-check: no complete answer for captain hold: %s\n' "$id" >&2
    return 1
  }
  printf '%s\n' "$answer"
}

case "${1:-}" in
  '') detect_rulings ;;
  --install) [ "$#" -eq 1 ] || exit 2; install_check ;;
  --answer) shift; answer_for_hold "$@" ;;
  *) exit 2 ;;
esac
